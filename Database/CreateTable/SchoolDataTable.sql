		irs.WHISTLEBLOWER_POLICY AS WHISTLEBLOWER_POLICY,
		irs.CEO_REVIEWED_COMPENSATION AS CEO_REVIEWED_COMPENSATION,
		irs.OTHER_REVIEWED_COMPENSATION AS OTHER_REVIEWED_COMPENSATION
	FROM `ipeds_2024_db`.`C2022_B` C2022B
	INNER JOIN `ipedsEF2022ByLevelOfStudent` EF2022F ON C2022B.UNITID = EF2022F.UNITID
	INNER JOIN `ipedsIC2022AssociateAndAbove` IC2022F ON C2022B.UNITID = IC2022F.UNITID
	INNER JOIN `ipedsHD2022TrimmedEIN` HD2022 ON C2022B.UNITID = HD2022.UNITID
	INNER JOIN `ipedsSAL2022ISBYAcademicRank` SAL2022ISRANK ON C2022B.UNITID = SAL2022ISRANK.UNITID
	INNER JOIN `ipedsS2022OCByOccupation` S2022OCOCCUPATION ON C2022B.UNITID = S2022OCOCCUPATION.UNITID
	INNER JOIN `ipedsS2022ISByAcademicRank` S2022ISRank ON C2022B.UNITID = S2022ISRank.UNITID
	INNER JOIN `cssYearly` css ON HD2022.OPEID = css.OPEID
	LEFT JOIN `irs990ByLatestDate` irs ON HD2022.EIN = irs.EIN
	WHERE C2022B.CSTOTLT >= 50 AND EF2022F.ENROLLTOT >= 200
	ORDER BY C2022B.`UNITID` ASC
) AS genderfair2024;
	